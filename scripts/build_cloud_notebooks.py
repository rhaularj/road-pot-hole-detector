def build(key: str, cfg: dict) -> dict:
    yolo = cfg["kind"] == "yolo"
    settings = (SETTINGS.replace("__KEY__", key).replace("__BATCH__", str(cfg["batch"]))
                .replace("__WEIGHTS_LINE__", f'WEIGHTS = "{cfg["weights"]}"   # COCO-pretrained, downloaded '
                                             f'automatically\n' if yolo else "")
                .replace("__DEVICE_NOTE__", '; "0,1" uses both Kaggle T4s' if yolo else "")
                .replace("__EXTRA_EXAMPLE__", "--set fraction=0.05" if yolo else "--fraction 0.05")
                .replace("__AMP_LINE__", "" if yolo else "AMP = True                # mixed precision on the GPU "
                                                         "(set False for GTX 16xx cards)\n"))
    scripts = ["utils.py", "fix_prepared_data.py"] + (["train.py", "evaluate.py"] if yolo
                                                     else ["train_faster_rcnn.py"])
    cells = [
        markdown_cell(INTRO.replace("__TITLE__", cfg["title"])),
        markdown_cell("## 1. Settings"),
        code_cell(settings),
        markdown_cell("## 2. Environment"),
        code_cell(SETUP),
        code_cell(INSTALL_YOLO if yolo else INSTALL_FRCNN),
        code_cell(GPU),
        markdown_cell("## 3. Project code\n\nThese cells are copies of the repository's `scripts/` and "
                      "`configs/` files."),
    ]
    cells += [writefile_cell(f"scripts/{name}", (PROJECT_ROOT / "scripts" / name).read_text(encoding="utf-8"))
              for name in scripts]
    cells.append(writefile_cell("configs/rdd2022.yaml",
                                (PROJECT_ROOT / "configs" / "rdd2022.yaml").read_text(encoding="utf-8")))
    cells += [
        markdown_cell("## 4. Data\n\nFinds the dataset, then writes a fixed copy (4 classes, leak-free block "
                      "split) to the working folder. Images are symlinked, so this is fast and small."),
        code_cell(DATA),
        markdown_cell("## 5. Train\n\nResumes automatically if a resumable checkpoint exists. Stops cleanly "
                      "after `MAX_HOURS`; run the notebook again to continue."),
        code_cell(RESUME_HELPERS),
        code_cell(TRAIN_YOLO if yolo else TRAIN_FRCNN),
        markdown_cell("## 6. Training curves"),
        code_cell(PLOT_YOLO if yolo else PLOT_FRCNN),
        markdown_cell("## 7. Evaluate on val and test\n\nF1 @ IoU 0.5 (the RDD challenge metric) and mAP@0.5, "
                      "overall and per class."),
        code_cell(EVAL_YOLO if yolo else EVAL_FRCNN),
        markdown_cell("## 8. Save outputs"),
        code_cell(SAVE),
    ]
    return notebook(cells)


def main():
    for key, cfg in MODELS.items():
        path = OUT_DIR / f"train_{key}.ipynb"
        save_notebook(build(key, cfg), path)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
